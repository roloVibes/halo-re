#!/usr/bin/env python3
"""Halo RE report generator.

Generates report/report.md from CONFIRMED finding records only. The
finding record is the source of truth; the report is a projection —
hand-edits are overwritten on regeneration. Every claim carries its
evidence reference. External publishing stays behind human review: this
tool writes a draft, nothing else.
"""
from __future__ import annotations

from pathlib import Path

from findings_store import FindingStore


class ReportError(Exception):
    pass


SEVERITY_ORDER = {"high": 0, "medium": 1, "low": 2, "info": 3}


def _severity(f: dict) -> str:
    sev = "info"
    rat = (f.get("reviewer_decision") or {}).get("severity_rationale", "")
    for k in SEVERITY_ORDER:
        if k in rat.lower():
            sev = k
            break
    return sev


def generate_report(store: FindingStore, *, actor: str = "hr-reporter") -> Path:
    confirmed = store.list_findings(status="confirmed")
    all_findings = store.list_findings()
    chain_problems = store.verify_chain()

    # Refuse to report on a broken evidence chain — an attestation has to
    # survive an auditor.
    if chain_problems:
        raise ReportError(
            "evidence chain verification failed; refusing to generate: "
            + "; ".join(chain_problems[:3]))

    # Coverage table: every finding appears with its status so nothing is
    # silently dropped from the record (only confirmed get sections).
    lines = ["# Reverse-Engineering Analysis Report (DRAFT)", ""]
    eng = store.engagement()
    lines += [
        f"**Engagement:** {eng['engagement_id']}",
        f"**Window:** {eng['window']['start']} → {eng['window']['expires']}",
        f"**Allowed activities:** {', '.join(eng['allowed_activities'])}",
        "",
        "## Executive summary",
        "",
        (f"{len(confirmed)} confirmed finding(s) out of {len(all_findings)} "
         "total finding(s) recorded this engagement."),
        "",
    ]

    if confirmed:
        lines += ["## Findings", ""]
        for f in sorted(confirmed, key=_severity):
            rd = f.get("reviewer_decision") or {}
            lines += [
                f"### {f['finding_id']} — {f['title']}",
                "",
                f"- **Category:** {f.get('category', 'n/a')}"
                + (f" (playbook: {f['playbook']['id']} v{f['playbook']['version']})"
                   if f.get("playbook") else ""),
                f"- **Binary:** {f.get('binary', 'n/a')}",
                f"- **Function:** {f.get('function', 'n/a')}"
                + (f" (CWE: {f['cwe']})" if f.get("cwe") else ""),
                f"- **Severity rationale:** {rd.get('severity_rationale', 'n/a')}",
                f"- **Confidence:** {rd.get('confidence', 'n/a')}",
                "",
                f"{f.get('description', '')}",
                "",
                "**Expected behavior:** " + f.get("expected_behavior", "n/a"),
                "",
                "**Observed behavior:** " + f.get("observed_behavior", "n/a"),
                "",
                "**Impact:** " + f.get("impact", "n/a"),
                "",
                "**Remediation:** " + f.get("remediation", "n/a"),
                "",
                "**Reproduction:**",
                "",
            ]
            for i, step in enumerate(f.get("reproduction", {}).get("steps", []), 1):
                lines.append(f"{i}. {step}")
            lines += ["", "**Evidence:**", ""]
            for ev in f.get("evidence", []):
                lines.append(f"- ledger row `{ev['ledger_ref']}` "
                             f"(artifact `{(ev.get('artifact_sha256') or '')[:12]}…`, "
                             f"kind: {ev.get('kind', 'n/a')})")
            lines.append("")

    # Coverage + limitations: every finding by status, nothing hidden.
    lines += ["## Finding coverage (all records)", "",
              "| Finding | Status |", "|---|---|"]
    for f in sorted(all_findings, key=lambda x: x["finding_id"]):
        lines.append(f"| {f['finding_id']} | {f['status']} |")
    lines += [
        "",
        "## Limitations",
        "",
        "- This report is generated from confirmed finding records; "
        "candidate, rejected, duplicate and not-reproduced observations "
        "are listed above but not detailed.",
        "- Draft only: external publication requires human review.",
        "",
        f"_Generated by {actor}; regeneration overwrites hand-edits._",
        "",
    ]

    out = store.report_dir / "report.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    return out
